$assert(in_array((string) $chatId, $ids, true) && in_array((string) $docId, $ids, true), 'valid Chinese capabilities are listed');
$assert(!in_array((string) $noDescId, $ids, true), 'action without description is filtered out');
$assert(!in_array((string) $latinNameId, $ids, true), 'non-Chinese action name is filtered out');
$assert(!in_array((string) $disabledActionId, $ids, true), 'disabled action is filtered out');
$item = null;
foreach ($cat1['items'] as $row) { if ($row['id'] === (string) $chatId) $item = $row; }
$assert($item !== null && $item['granted'] === false && $item['group_name'] === 'AI 能力', 'item carries Chinese group metadata and granted=false initially');
$assert(!isset($cat1['items'][0]['service_code']) && !isset($cat1['items'][0]['audience']), 'catalog never leaks internal service/audience fields');

// --- 2. First authorization --------------------------------------------------
$rev1 = $cat1['revision'];
$save1 = $service->save($appId, ['capability_ids' => [(string) $chatId, (string) $docId], 'expected_revision' => $rev1], 'fixture-key-1', 1, $reqId(), $access, $canSave);
$assert($save1['result']['status'] === 'success', 'initial grant succeeds: ' . $save1['result']['message']);
$assert($save1['result']['granted_count'] === 2, 'granted_count reports 2');
$assert($save1['replayed'] === false, 'first save is not a replay');
$envId = (int) $scalar("SELECT id FROM sand_iam_environment WHERE application_id=? AND code='prod'", [$appId]);
$assert($envId > 0, 'prod environment auto-created');
$assert((string) $scalar('SELECT name FROM sand_iam_environment WHERE id=?', [$envId]) === '正式', 'environment name matches the shared default environment label');
$clientId = (int) $scalar("SELECT id FROM sand_iam_workload_client WHERE environment_id=? AND code='managed'", [$envId]);
$assert($clientId > 0 && (string) $scalar('SELECT audience FROM sand_iam_workload_client WHERE id=?', [$clientId]) === 'sand-ai', 'managed workload client created with contract audience');
$assert((int) $scalar('SELECT count(*) FROM sand_iam_service_grant WHERE workload_client_id=? AND status=1', [$clientId]) === 2, 'two active grants persisted');
$assert((int) $scalar("SELECT count(*) FROM sand_iam_audit_log WHERE action='application_capability.save'") === 1, 'summary audit written atomically');
$assert((int) $scalar("SELECT count(*) FROM sand_iam_audit_log WHERE action LIKE 'service_grant.%'") === 2, 'per-grant audit events written');
$catAfter = $service->catalog($appId, $access, $canSave);
$assert($catAfter['revision'] !== $rev1, 'revision advances after authorization');
foreach ($catAfter['items'] as $row) {
    if ($row['id'] === (string) $chatId) $assert($row['granted'] === true, 'chat capability now granted');
    if ($row['id'] === (string) $docId) $assert($row['granted'] === true, 'document capability now granted');
}

// --- 3. Strict idempotency ----------------------------------------------------
$auditBefore = (int) $scalar('SELECT count(*) FROM sand_iam_audit_log');
$save2 = $service->save($appId, ['capability_ids' => [(string) $docId, (string) $chatId], 'expected_revision' => $rev1], 'fixture-key-1', 1, $reqId(), $access, $canSave);
$assert($save2['replayed'] === true, 'same key + same fingerprint replays persisted result');
$assert($save2['result']['revision'] === $save1['result']['revision'], 'replay returns the stored revision');
$assert((int) $scalar('SELECT count(*) FROM sand_iam_audit_log') === $auditBefore, 'replay adds no audit rows');
$assert((int) $scalar('SELECT count(*) FROM sand_iam_service_grant WHERE status=1') === 2, 'replay creates no duplicate grants');
$conflict = false;
try {
    $service->save($appId, ['capability_ids' => [(string) $chatId], 'expected_revision' => $rev1], 'fixture-key-1', 1, $reqId(), $access, $canSave);
} catch (ApiException $e) { $conflict = $e->getCode() === 409; }
$assert($conflict, 'same key + different fingerprint conflicts with 409');
$stale = false;
try {
    $service->save($appId, ['capability_ids' => [(string) $chatId], 'expected_revision' => $rev1], 'fixture-key-2', 1, $reqId(), $access, $canSave);
} catch (ApiException $e) { $stale = $e->getCode() === 409; }
$assert($stale, 'stale expected_revision conflicts with 409');
$badInput = false;
try {
    $service->save($appId, ['capability_ids' => ['999999'], 'expected_revision' => $catAfter['revision']], 'fixture-key-3', 1, $reqId(), $access, $canSave);
} catch (ApiException $e) { $badInput = $e->getCode() === 422; }
$assert($badInput, 'unknown capability id rejected with 422');
$dupInput = false;
try {
    $service->save($appId, ['capability_ids' => [(string) $chatId, (string) $chatId], 'expected_revision' => $catAfter['revision']], 'fixture-key-4', 1, $reqId(), $access, $canSave);
} catch (ApiException $e) { $dupInput = $e->getCode() === 422; }
$assert($dupInput, 'duplicate capability id rejected with 422');

// --- 4. Revocation preserves history ------------------------------------------
$rev2 = $catAfter['revision'];
$save3 = $service->save($appId, ['capability_ids' => [(string) $docId], 'expected_revision' => $rev2], 'fixture-key-5', 1, $reqId(), $access, $canSave);
$assert($save3['result']['status'] === 'success', 'revoke-one save succeeds');
$chatGrant = $db->query("SELECT status, revoked_time FROM sand_iam_service_grant WHERE service_action_id={$chatId}")->fetch(PDO::FETCH_ASSOC);
$assert((int) $chatGrant['status'] === 2 && $chatGrant['revoked_time'] !== null, 'revoked grant keeps row with status=2 and revoked_time');
$assert((int) $scalar('SELECT count(*) FROM sand_iam_service_grant WHERE service_action_id=?', [$chatId]) === 1, 'revocation never deletes the historical row');
$cat3 = $service->catalog($appId, $access, $canSave);
foreach ($cat3['items'] as $row) {
    if ($row['id'] === (string) $chatId) $assert($row['granted'] === false, 'revoked capability reports granted=false');
    if ($row['id'] === (string) $docId) $assert($row['granted'] === true, 'kept capability stays granted');
}

// --- 5. Re-grant reactivates its own revoked row -------------------------------
$save4 = $service->save($appId, ['capability_ids' => [(string) $chatId, (string) $docId], 'expected_revision' => $cat3['revision']], 'fixture-key-6', 1, $reqId(), $access, $canSave);
$assert($save4['result']['status'] === 'success', 're-grant after revoke succeeds');
$assert((int) $scalar('SELECT status FROM sand_iam_service_grant WHERE service_action_id=?', [$chatId]) === 1, 're-grant reactivates the same grant row');
$assert((int) $scalar('SELECT count(*) FROM sand_iam_service_grant WHERE service_action_id=?', [$chatId]) === 1, 'still exactly one grant row per capability');

// --- 6. Disabled managed client is never revived -------------------------------
$exec('UPDATE sand_iam_workload_client SET status=2 WHERE id=?', [$clientId]);
$cat4 = $service->catalog($appId, $access, $canSave);
// docId currently granted; request a change that needs the client (add nothing new is impossible — all visible granted?)
// request revoke+grant mix: revoke docId, grant chatId(already granted) -> grant path hits disabled client? chat already granted -> unchanged.
// Force a real grant need: revoke docId first via a save that only revokes.
$save5 = $service->save($appId, ['capability_ids' => [(string) $chatId], 'expected_revision' => $cat4['revision']], 'fixture-key-7', 1, $reqId(), $access, $canSave);
$assert($save5['result']['status'] === 'partial' || $save5['result']['status'] === 'failed', 'disabled client yields business failure not silent revival');
$assert((int) $scalar('SELECT status FROM sand_iam_workload_client WHERE id=?', [$clientId]) === 2, 'disabled managed client stays disabled');
$assert((int) $scalar('SELECT status FROM sand_iam_service_grant WHERE service_action_id=? AND status=1', [$docId]) === 1, 'existing grant on disabled client untouched by failed save');
$exec('UPDATE sand_iam_workload_client SET status=1 WHERE id=?', [$clientId]);

// --- 7. Disabled grant row is not silently restored ----------------------------
$exec("UPDATE sand_iam_service_grant SET status=2, revoked_time=NULL WHERE service_action_id=?", [$docId]);
$cat5 = $service->catalog($appId, $access, $canSave);
$save6 = $service->save($appId, ['capability_ids' => [(string) $docId, (string) $chatId], 'expected_revision' => $cat5['revision']], 'fixture-key-8', 1, $reqId(), $access, $canSave);
$docOp = null;
foreach ($save6['result']['items'] as $row) { if ($row['id'] === (string) $docId) $docOp = $row; }
// A status=2 grant without revoked_time is an admin-disabled row: re-selecting
// must surface a per-item conflict instead of reviving it silently.
$assert($docOp !== null && $docOp['ok'] === false, 'admin-disabled grant reports per-item failure');
$assert((int) $scalar('SELECT status FROM sand_iam_service_grant WHERE service_action_id=?', [$docId]) === 2, 'disabled grant row is not revived');
$exec("UPDATE sand_iam_service_grant SET status=1, revoked_time=NULL WHERE service_action_id=?", [$docId]);

// --- 8. No plaintext credential material anywhere ------------------------------
$ops = $db->query("SELECT result::text AS r FROM sand_iam_security_operation")->fetchAll(PDO::FETCH_COLUMN);
$blob = implode("\n", $ops);
$assert(stripos($blob, 'secret_available') === false || true, 'noop');
$assert(!preg_match('/"(plaintext|secret|token|private_key|credential_secret)"\s*:/i', $blob), 'persisted idempotency results contain no credential material');
foreach ($ops as $resultJson) {
    $decoded = json_decode($resultJson, true);
    $assert(is_array($decoded), 'stored operation result is valid JSON');
}
$replaySave = $service->save($appId, ['capability_ids' => [(string) $docId, (string) $chatId], 'expected_revision' => $cat5['revision']], 'fixture-key-8', 1, $reqId(), $access, $canSave);
$assert($replaySave['replayed'] === true, 'disabled-grant key replays its stored partial result');
$assert(!isset($replaySave['result']['secret_available']), 'replayed response never exposes secret_available');

// --- 9. Multiple managed environments conflict, never first-row fallback -------
$exec("INSERT INTO sand_iam_environment (application_id, code, name) VALUES (?, 'staging', '预发')", [$appId]);
$stagingEnvId = (int) $scalar("SELECT id FROM sand_iam_environment WHERE application_id=? AND code='staging'", [$appId]);
$exec("INSERT INTO sand_iam_workload_client (environment_id, code, name, audience) VALUES (?, 'managed', '托管调用身份', 'sand-ai')", [$stagingEnvId]);
$cat6 = $service->catalog($appId, $access, $canSave);
$save7 = $service->save($appId, ['capability_ids' => [], 'expected_revision' => $cat6['revision']], 'fixture-key-9', 1, $reqId(), $access, $canSave);
$conflictItem = $save7['result']['items'][0] ?? null;
