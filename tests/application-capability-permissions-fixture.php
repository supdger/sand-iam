<?php

declare(strict_types=1);

/**
 * 0.9.7 migration-045 role-inheritance fixture (development-only; never ships
 * in the release payload — `tests/` is outside the payload roots).
 *
 * Replays migrations/045_application_capability_permissions.pgsql verbatim
 * against a scratch PostgreSQL database seeded with the minimal
 * sand_system_menu / sand_system_role_menu / sand_iam_schema_migration shape
 * the migration touches, then asserts the split inheritance contract:
 *
 *   capability:index follows SandIAMConnection, application:index and every
 *     existing application/grant write slug (writers must see the page);
 *   capability:save follows only SandIAMConnection and the grant/application
 *     write slugs — a view-only application role must never gain writes.
 *
 * Usage:
 *
 *   php tests/application-capability-permissions-fixture.php
 *
 * The scratch database is created and dropped by this script; pass a PDO pgsql
 * admin DSN via SAND_IAM_FIXTURE_ADMIN_DSN (default local trust socket).
 */

$adminDsn = getenv('SAND_IAM_FIXTURE_ADMIN_DSN') ?: 'pgsql:host=127.0.0.1;port=5432;dbname=postgres';
$adminUser = getenv('SAND_IAM_FIXTURE_ADMIN_USER') ?: (string) (getenv('USER') ?: 'postgres');
$adminPass = getenv('SAND_IAM_FIXTURE_ADMIN_PASSWORD') ?: '';
$fixtureDb = 'sandiam_045_fixture_' . getmypid();

$fail = static function (string $message): never {
    fwrite(STDERR, "[FAIL] {$message}\n");
    exit(1);
};

$admin = new PDO($adminDsn, $adminUser, $adminPass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$admin->exec('DROP DATABASE IF EXISTS ' . $fixtureDb . ' WITH (FORCE)');
$admin->exec('CREATE DATABASE ' . $fixtureDb);

$fixtureDropped = false;
$dropFixture = static function () use ($adminDsn, $adminUser, $adminPass, $fixtureDb): void {
    $pdo = new PDO($adminDsn, $adminUser, $adminPass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
    $pdo->exec('DROP DATABASE IF EXISTS ' . $fixtureDb . ' WITH (FORCE)');
};
register_shutdown_function(static function () use (&$fixtureDropped, $dropFixture): void {
    if ($fixtureDropped) return;
    try { $dropFixture(); } catch (Throwable $e) { fwrite(STDERR, "[WARN] scratch cleanup failed: {$e->getMessage()}\n"); }
});

$db = new PDO(
    'pgsql:host=127.0.0.1;port=5432;dbname=' . $fixtureDb,
    $adminUser,
    $adminPass,
    [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
);

$assert = static function (bool $cond, string $message) use ($fail): void {
    if (!$cond) $fail($message);
    echo "[PASS] {$message}\n";
};
$exec = static function (string $sql, array $args = []) use ($db): void {
    $db->prepare($sql)->execute($args);
};
$scalar = static function (string $sql, array $args = []) use ($db): mixed {
    $st = $db->prepare($sql);
    $st->execute($args);
    return $st->fetchColumn();
};

$db->exec(<<<'SQL'
CREATE TABLE sand_iam_schema_migration (
    migration_file varchar(160) PRIMARY KEY,
    revision integer NOT NULL,
    checksum char(64) NOT NULL,
    package_version varchar(32) NOT NULL,
    executed_time timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE sand_system_menu (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint NOT NULL DEFAULT 0,
    name varchar(128) NOT NULL,
    code varchar(128) NOT NULL DEFAULT '',
    slug varchar(128) NOT NULL DEFAULT '',
    type smallint NOT NULL DEFAULT 1,
    path varchar(255) NOT NULL DEFAULT '',
    component varchar(255) NOT NULL DEFAULT '',
    icon varchar(64) NOT NULL DEFAULT '',
    sort integer NOT NULL DEFAULT 0,
    is_hidden smallint NOT NULL DEFAULT 0,
    status smallint NOT NULL DEFAULT 1,
    create_time timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time timestamp(0) NULL
);
CREATE TABLE sand_system_role_menu (
    role_id bigint NOT NULL,
    menu_id bigint NOT NULL
);
SQL);

// --- Seed: complete 001-044 ledger the migration requires -------------------
// The published ledger holds 45 rows before revision045 (the historical
// double-numbered 006 pair makes 001-044 span 45 files); only the 044 row's
// identity is verified, the rest just pad the count.
$stmt = $db->prepare('INSERT INTO sand_iam_schema_migration (migration_file, revision, checksum, package_version) VALUES (?, ?, ?, ?)');
for ($i = 1; $i <= 44; $i++) {
    $name = sprintf('000_fixture_migration_%02d.pgsql', $i);
    $stmt->execute([$name, $i, str_repeat(dechex($i % 16), 64), '0.7.3']);
}
$stmt->execute(['044_application_capability_directory.pgsql', 44, str_repeat('a', 64), '0.9.7']);
$assert((int) $scalar('SELECT count(*) FROM sand_iam_schema_migration') === 45, 'seeded 001-044 migration ledger');

// --- Seed: menu tree ---------------------------------------------------------
// SandIAM root -> SandIAMConnection page (exactly one active candidate).
$exec("INSERT INTO sand_system_menu (parent_id, name, code, slug, type, path, component, sort, is_hidden, status) VALUES (0, 'SandIAM', 'SandIAM', '', 1, '', '', 10, 0, 1)");
$rootId = (int) $scalar("SELECT id FROM sand_system_menu WHERE code='SandIAM'");
$exec("INSERT INTO sand_system_menu (parent_id, name, code, slug, type, path, component, sort, is_hidden, status) VALUES (?, 'SandIAM 接入', 'SandIAMConnection', '', 2, '/sand-iam', 'sand-iam', 20, 0, 1)", [$rootId]);
$connId = (int) $scalar("SELECT id FROM sand_system_menu WHERE code='SandIAMConnection'");

// Existing permission nodes roles may already hold (type 3).
$menuId = static function (string $slug) use ($exec, $scalar, $connId): int {
    $exec("INSERT INTO sand_system_menu (parent_id, name, code, slug, type, sort, is_hidden, status) VALUES (?, ?, ?, ?, 3, 100, 1, 1)",
        [$connId, $slug, $slug, $slug]);
    return (int) $scalar('SELECT id FROM sand_system_menu WHERE slug=?', [$slug]);
};
$appIndexId = $menuId('sand_iam:application:index');
$appReadId = $menuId('sand_iam:application:read');
$appSaveId = $menuId('sand_iam:application:save');
$appUpdateId = $menuId('sand_iam:application:update');
$grantIndexId = $menuId('sand_iam:grant:index');
$grantSaveId = $menuId('sand_iam:grant:save');

// --- Seed: roles holding exactly one source each -----------------------------
$grant = static function (int $roleId, int $menuId) use ($exec): void {
    $exec('INSERT INTO sand_system_role_menu (role_id, menu_id) VALUES (?, ?)', [$roleId, $menuId]);
};
$grant(1, $connId);          // connection page holder -> both nodes
$grant(2, $appIndexId);      // application list viewer -> index only
$grant(3, $appReadId);       // application detail viewer -> neither
$grant(4, $grantSaveId);     // service-grant writer -> both nodes
$grant(5, $appSaveId);       // application creator -> both nodes
$grant(6, $appUpdateId);     // application editor -> both nodes
$grant(7, $grantIndexId);    // service-grant viewer -> neither
$grant(8, $appIndexId);      // second application viewer -> index only
$grant(8, $grantIndexId);    // plus grant viewer -> still index only

// --- Run the real migration file --------------------------------------------
$migration = file_get_contents(dirname(__DIR__) . '/migrations/045_application_capability_permissions.pgsql');
if (!is_string($migration) || trim($migration) === '') $fail('migration 045 source unreadable');
$db->exec($migration);

// --- Assertions ---------------------------------------------------------------
$capIndexId = (int) $scalar("SELECT id FROM sand_system_menu WHERE slug='sand_iam:application_capability:index'");
$capSaveId = (int) $scalar("SELECT id FROM sand_system_menu WHERE slug='sand_iam:application_capability:save'");
$assert($capIndexId > 0 && $capSaveId > 0, 'migration seeds both hidden capability permission nodes');
$assert((int) $scalar("SELECT count(*) FROM sand_system_menu WHERE slug LIKE 'sand_iam:application_capability:%' AND type=3 AND is_hidden=1 AND status=1 AND parent_id=?", [$connId]) === 2,
    'capability nodes are hidden type-3 permissions under SandIAMConnection');
$assert((int) $scalar('SELECT count(*) FROM sand_iam_schema_migration') === 46, 'ledger advances to 46 rows');
$assert((int) $scalar("SELECT revision FROM sand_iam_schema_migration WHERE migration_file='045_application_capability_permissions.pgsql'") === 45, 'ledger records revision 45');

$hasGrant = static function (int $roleId, int $menuId) use ($scalar): bool {
    return (int) $scalar('SELECT count(*) FROM sand_system_role_menu WHERE role_id=? AND menu_id=?', [$roleId, $menuId]) === 1;
};

// index node expectations
foreach ([1, 2, 4, 5, 6, 8] as $roleId) {
    $assert($hasGrant($roleId, $capIndexId), "role {$roleId} inherits capability:index");
}
foreach ([3, 7] as $roleId) {
    $assert(!$hasGrant($roleId, $capIndexId), "role {$roleId} does not inherit capability:index");
}
// save node expectations — the audit B3 fix: view-only roles stay view-only
foreach ([1, 4, 5, 6] as $roleId) {
    $assert($hasGrant($roleId, $capSaveId), "role {$roleId} inherits capability:save");
}
foreach ([2, 3, 7, 8] as $roleId) {
    $assert(!$hasGrant($roleId, $capSaveId), "role {$roleId} must NOT inherit capability:save");
}

// --- Idempotent rerun ---------------------------------------------------------
$db->exec($migration);
$assert((int) $scalar('SELECT count(*) FROM sand_iam_schema_migration') === 46, 'rerun keeps the 46-row ledger');
$assert((int) $scalar('SELECT count(*) FROM sand_system_role_menu rm JOIN sand_system_menu m ON m.id=rm.menu_id WHERE m.slug LIKE \'sand_iam:application_capability:%\'') === 10,
    'rerun grants no duplicate capability role_menu rows');

$db = null;
unset($exec, $scalar, $menuId, $grant, $hasGrant, $assert);
$dropFixture();
$fixtureDropped = true;
echo "ALL FIXTURE ASSERTIONS PASSED; scratch database {$fixtureDb} dropped\n";
