<?php

declare(strict_types=1);

/**
 * ServiceGrantQuery read-only port fixture (development-only; never ships in
 * the release payload — `tests/` is outside the payload roots).
 *
 * Exercises plugin\SandIam\app\runtime\ServiceGrantQuery::hasActiveGrant
 * against a real scratch PostgreSQL database, covering the exact WHERE
 * semantics shared with IdentityContextProvider::resolveServiceGrants:
 * active grant, disabled grant, revoked grant, expired/unexpired expiry,
 * wrong service, wrong action, wrong audience and wrong workload client.
 *
 * Usage:
 *
 *   SAND_IAM_FIXTURE_AUTOLOAD=/path/to/think-orm/vendor/autoload.php \
 *   php tests/service-grant-query-fixture.php
 *
 * The scratch database is created and dropped by this script; pass a PDO pgsql
 * admin DSN via SAND_IAM_FIXTURE_ADMIN_DSN (default local trust socket).
 */

$adminDsn = getenv('SAND_IAM_FIXTURE_ADMIN_DSN') ?: 'pgsql:host=127.0.0.1;port=5432;dbname=postgres';
$adminUser = getenv('SAND_IAM_FIXTURE_ADMIN_USER') ?: (string) (getenv('USER') ?: 'postgres');
$adminPass = getenv('SAND_IAM_FIXTURE_ADMIN_PASSWORD') ?: '';
$fixtureDb = 'sandiam_grantq_fixture_' . getmypid();

$fail = static function (string $message): never {
    fwrite(STDERR, "[FAIL] {$message}\n");
    exit(1);
};

$ormAutoload = getenv('SAND_IAM_FIXTURE_AUTOLOAD') ?: '/tmp/iam-fixture-vendor/vendor/autoload.php';
if (!is_file($ormAutoload)) {
    $fail('think-orm autoload not found; set SAND_IAM_FIXTURE_AUTOLOAD to a composer install of topthink/think-orm');
}
require $ormAutoload;

$root = dirname(__DIR__);
spl_autoload_register(static function (string $class) use ($root): void {
    $prefix = 'plugin\\SandIam\\app\\';
    if (str_starts_with($class, $prefix)) {
        $file = $root . '/plugin/sand-iam/app/' . str_replace('\\', '/', substr($class, strlen($prefix))) . '.php';
        if (is_file($file)) require $file;
    }
});

$admin = new PDO($adminDsn, $adminUser, $adminPass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$admin->exec('DROP DATABASE IF EXISTS ' . $fixtureDb . ' WITH (FORCE)');
$admin->exec('CREATE DATABASE ' . $fixtureDb);

$fixtureDropped = false;
$dropFixture = static function () use ($adminDsn, $adminUser, $adminPass, $fixtureDb): void {
    $pdo = new PDO($adminDsn, $adminUser, $adminPass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
    $pdo->exec('DROP DATABASE IF EXISTS ' . $fixtureDb . ' WITH (FORCE)');
};
register_shutdown_function(static function () use (&$fixtureDropped, $dropFixture): void {
    if ($fixtureDropped) return;
    try { $dropFixture(); } catch (Throwable $e) { fwrite(STDERR, "[WARN] scratch cleanup failed: {$e->getMessage()}\n"); }
});

$db = new PDO(
    'pgsql:host=127.0.0.1;port=5432;dbname=' . $fixtureDb,
    $adminUser,
    $adminPass,
    [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
);

// think-orm bootstrap bound to the scratch database.
$manager = new \think\DbManager();
$manager->setConfig([
    'default' => 'pgsql',
    'connections' => [
        'pgsql' => [
            'type' => 'pgsql',
            'hostname' => '127.0.0.1',
            'database' => $fixtureDb,
            'username' => $adminUser,
            'password' => $adminPass,
            'hostport' => '5432',
            'charset' => 'utf8',
            'prefix' => '',
            'debug' => false,
            'fields_strict' => true,
        ],
    ],
]);
$container = \think\Container::getInstance();
$container->instance('think\\DbManager', $manager);

$assert = static function (bool $cond, string $message) use ($fail): void {
    if (!$cond) $fail($message);
    echo "[PASS] {$message}\n";
};
$exec = static function (string $sql, array $args = []) use ($db): void {
    $db->prepare($sql)->execute($args);
};
$scalar = static function (string $sql, array $args = []) use ($db): mixed {
    $st = $db->prepare($sql);
    $st->execute($args);
    return $st->fetchColumn();
};

$db->exec(<<<'SQL'
CREATE TABLE sand_iam_service (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL, name varchar(128) NOT NULL,
    status smallint NOT NULL DEFAULT 1 CHECK (status IN (1,2)),
    create_time timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time timestamp(0) NULL
);
CREATE TABLE sand_iam_service_action (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id bigint NOT NULL REFERENCES sand_iam_service(id),
    code varchar(96) NOT NULL, name varchar(128) NOT NULL,
    status smallint NOT NULL DEFAULT 1 CHECK (status IN (1,2)),
    create_time timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time timestamp(0) NULL
);
CREATE TABLE sand_iam_service_grant (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_client_id bigint NOT NULL,
    service_action_id bigint NOT NULL REFERENCES sand_iam_service_action(id),
    audience varchar(128) NOT NULL,
    status smallint NOT NULL DEFAULT 1 CHECK (status IN (1,2)),
    expire_time timestamp(0) NULL, revoked_time timestamp(0) NULL,
    create_time timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time timestamp(0) NULL
);
SQL);

// One service, one sibling service, and one action per scenario so every case
// is isolated. workload_client_id 42 is an arbitrary foreign value — the port
// never joins the client table, exactly like resolveServiceGrants.
$exec("INSERT INTO sand_iam_service (code, name) VALUES ('sand_ai', 'SandAI'), ('other_svc', 'Other')");
$sandAiId = (int) $scalar("SELECT id FROM sand_iam_service WHERE code='sand_ai'");
$otherSvcId = (int) $scalar("SELECT id FROM sand_iam_service WHERE code='other_svc'");
$seedAction = static function (int $serviceId, string $code, int $status = 1) use ($exec): int {
    $exec('INSERT INTO sand_iam_service_action (service_id, code, name, status) VALUES (?, ?, ?, ?)',
        [$serviceId, $code, $code, $status]);
    return (int) \think\facade\Db::table('sand_iam_service_action')->where('code', $code)->value('id');
};
$grant = static function (int $clientId, int $actionId, string $audience, array $opts = []) use ($exec): void {
    $exec('INSERT INTO sand_iam_service_grant (workload_client_id, service_action_id, audience, status, expire_time, revoked_time) VALUES (?, ?, ?, ?, ?, ?)', [
        $clientId, $actionId, $audience,
        $opts['status'] ?? 1,
        $opts['expire_time'] ?? null,
        $opts['revoked_time'] ?? null,
    ]);
};

$CLIENT = 42;
$AUDIENCE = 'sand-ai';

$activeAction = $seedAction($sandAiId, 'sand_ai.chat.complete');
$grant($CLIENT, $activeAction, $AUDIENCE);

$disabledGrantAction = $seedAction($sandAiId, 'sand_ai.disabled.grant');
$grant($CLIENT, $disabledGrantAction, $AUDIENCE, ['status' => 2]);

$revokedAction = $seedAction($sandAiId, 'sand_ai.revoked');
$grant($CLIENT, $revokedAction, $AUDIENCE, ['revoked_time' => '2020-01-01 00:00:00']);

$expiredAction = $seedAction($sandAiId, 'sand_ai.expired');
$grant($CLIENT, $expiredAction, $AUDIENCE, ['expire_time' => '2020-01-01 00:00:00']);

$futureExpiryAction = $seedAction($sandAiId, 'sand_ai.future.expiry');
$grant($CLIENT, $futureExpiryAction, $AUDIENCE, ['expire_time' => '2999-01-01 00:00:00']);

$otherServiceAction = $seedAction($otherSvcId, 'other_svc.action');
$grant($CLIENT, $otherServiceAction, $AUDIENCE);

$disabledAction = $seedAction($sandAiId, 'sand_ai.disabled.action', 2);
$grant($CLIENT, $disabledAction, $AUDIENCE);

$disabledServiceAction = $seedAction($sandAiId, 'sand_ai.disabled.service.action');
$exec('UPDATE sand_iam_service SET status=2 WHERE id=?', [$otherSvcId]);
// other_svc is now disabled; its action grant must not resolve under it.

$query = new \plugin\SandIam\app\runtime\ServiceGrantQuery();

$assert($query->hasActiveGrant($CLIENT, $AUDIENCE, 'sand_ai', 'sand_ai.chat.complete') === true,
    'active grant resolves as active');
$assert($query->hasActiveGrant($CLIENT, $AUDIENCE, 'sand_ai', 'sand_ai.future.expiry') === true,
    'grant with a future expire_time resolves as active');
$assert($query->hasActiveGrant($CLIENT, $AUDIENCE, 'sand_ai', 'sand_ai.disabled.grant') === false,
    'status=2 grant does not resolve');
$assert($query->hasActiveGrant($CLIENT, $AUDIENCE, 'sand_ai', 'sand_ai.revoked') === false,
    'revoked grant does not resolve');
$assert($query->hasActiveGrant($CLIENT, $AUDIENCE, 'sand_ai', 'sand_ai.expired') === false,
    'expired grant does not resolve');
$assert($query->hasActiveGrant($CLIENT, $AUDIENCE, 'sand_ai', 'other_svc.action') === false,
    'grant on another service does not resolve under sand_ai');
$assert($query->hasActiveGrant($CLIENT, $AUDIENCE, 'other_svc', 'other_svc.action') === false,
    'grant on a disabled service does not resolve');
$assert($query->hasActiveGrant($CLIENT, $AUDIENCE, 'sand_ai', 'sand_ai.chat.complete.extra') === false,
    'unknown action code does not resolve');
$assert($query->hasActiveGrant($CLIENT, 'other-audience', 'sand_ai', 'sand_ai.chat.complete') === false,
    'wrong audience does not resolve');
$assert($query->hasActiveGrant(99, $AUDIENCE, 'sand_ai', 'sand_ai.chat.complete') === false,
    'wrong workload client does not resolve');
$assert($query->hasActiveGrant($CLIENT, $AUDIENCE, 'sand_ai', 'sand_ai.disabled.action') === false,
    'disabled action does not resolve');

$db = null;
unset($query, $exec, $scalar, $seedAction, $grant, $assert);
$dropFixture();
$fixtureDropped = true;
echo "ALL FIXTURE ASSERTIONS PASSED; scratch database {$fixtureDb} dropped\n";
